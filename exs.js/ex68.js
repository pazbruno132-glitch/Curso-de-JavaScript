let nivel = 3;

switch (nivel) {
  case 1:
    console.log("Acesso básico");
    break;

  case 2:
    console.log("Acesso intermediário");
    break;

  case 3:
    console.log("Acesso avançado");
    break;

  case 4:
    console.log("Acesso administrador");
    break;

  default:
    console.log("Nível inválido");
}
